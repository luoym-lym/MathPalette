from local_env import *
import argparse, json, hashlib, copy, importlib.util

ap=argparse.ArgumentParser()
ap.add_argument('mode', choices=['context','render','replay','eligibility'])
ap.add_argument('qid')
ap.add_argument('--candidate')
args=ap.parse_args()
assignment=read_json(OWN/'assignment.json')
assigned=next(x for x in assignment['questions'] if x['question_id']==args.qid)
qid=args.qid
branch=assigned['branch']

def eligible(stage):
    from dataset_tools import catalog
    record=next(x for x in catalog.rows(PROJECT/branch/'dataset.jsonl') if x['id']==qid)
    approval=read_json(PROJECT/'provenance/approvals.json')['approvals'][qid]
    current=catalog.digest(catalog.content(PROJECT,branch,record))
    accepted=[]; collected=[]; reasons=[]
    state_hashes={}
    for leaf,out in [('accepted_index.jsonl',accepted),('collected_index.jsonl',collected)]:
        path=PROJECT/branch/'special_variant'/leaf
        state_hashes[str(path)]=sha(path) if path.exists() else None
        if path.exists():
            for row in catalog.rows(path):
                if row.get('question_id',row.get('id'))==qid: out.append(row)
    recipes_path=PROJECT/branch/'special_variant'/qid/'recipes.json'
    collection_path=recipes_path.with_name('collection.json')
    recipes=read_json(recipes_path) if recipes_path.exists() else []
    collection=read_json(collection_path) if collection_path.exists() else None
    for p in [recipes_path,collection_path,PROJECT/branch/'dataset.jsonl',PROJECT/'provenance/approvals.json']:
        state_hashes[str(p)]=sha(p) if p.exists() else None
    if record!=assigned['formal_record']: reasons.append('formal_record_changed')
    if record['source_dataset']!='MathVision': reasons.append('source_not_MathVision')
    if current!=approval['content_sha256'] or current!=assigned['current_content_sha256'] or approval.get('reviewer')!='user': reasons.append('approval_content_changed')
    if accepted or collected or recipes or collection: reasons.append('existing_Special_or_completion')
    source={}
    for rel,expected in assigned['frozen_source_files_sha256'].items():
        actual=sha(PROJECT/rel); source[rel]=actual
        if actual!=expected: reasons.append('frozen_source_changed:'+rel)
    evidence={'checked_at':now(),'stage':stage,'question_id':qid,'eligible':not reasons,'reasons':reasons,
              'formal_record':record,'approval':approval,'current_content_sha256':current,
              'accepted_entries':accepted,'collected_entries':collected,'recipes':recipes,'collection':collection,
              'frozen_source_files_sha256':source,'authoritative_state_hashes':state_hashes}
    return evidence

root=OWN/qid
if args.mode=='eligibility':
    out=Path(args.candidate) if args.candidate else root
    ev=eligible('fresh_check')
    save(out/('eligibility_'+str(__import__('time').time_ns())+'.json'),ev,True)
    print(json.dumps({'eligible':ev['eligible'],'reasons':ev['reasons']},ensure_ascii=False))
    raise SystemExit(0 if ev['eligible'] else 2)

isolation=install_render_isolation()
sys.path.insert(0,str(PROJECT/branch/'workbench'))
from workbench_io import load_config, environment_versions, pixel_hash
from partial_style import object_paths, describe_paths
if branch=='SolidGeometry':
    from delivery_bridge_adapter import RendererAdapter
    from render_plugins import PluginRenderer
else:
    from mathvision_adapter import RendererAdapter
    from mathvision_plugins import PluginRenderer
from dataset_tools.mathvision_workbench import png_bytes

config=load_config()
config['runtime_dir']=str(OWN/'ownruntime'/'state')
config['output_dir']=str(OWN/'ownruntime'/'unused_output')
adapter=RendererAdapter(config)
metadata=adapter.inspect_question(qid)
scene=adapter.scene(qid)
try:
    scene.fig.canvas.draw()
    # The drawing is generated by the original adapter only. These are native paths.
    paths={o['id']:describe_paths(scene,o['id']) for o in scene.objects if o.get('styleable')}
    def plain(value):
        if hasattr(value,'tolist'): return plain(value.tolist())
        if isinstance(value,dict): return {k:plain(v) for k,v in value.items() if k not in ('path','artist')}
        if isinstance(value,(list,tuple)): return [plain(v) for v in value]
        return value
    raw_paths={o['id']:[plain(p) for p in object_paths(scene,o['id'])] for o in scene.objects if o.get('styleable')}
    meta_bounds={'xlim':list(scene.ax.get_xlim()),'ylim':list(scene.ax.get_ylim())}
    metadata.update(meta_bounds)
    original=png_bytes(scene)
    assert pixel_hash(original)==pixel_hash(PROJECT/branch/assigned['formal_record']['image'])
finally:
    scene.close()

if args.mode=='context':
    ev=eligible('before_design')
    save(root/'eligibility_before_design.json',ev,True)
    save(root/'formal_record.json',ev['formal_record'],True)
    assert ev['eligible'], ev['reasons']
    save(root/'context.json',metadata,True)
    save(root/'path_fingerprints.json',paths,True)
    save(root/'raw_paths.json',raw_paths,True)
    native_scene=read_json(PROJECT/branch/assigned['formal_record']['scene'])
    save(root/'source_scene_snapshot.json',native_scene,True)
    (root/'noop.png').write_bytes(original)
    save(root/'baseline_check.json',{'noop_pixels_equal':True,'formal_png_sha256':sha(PROJECT/branch/assigned['formal_record']['image']),
                                   'noop_png_sha256':sha(root/'noop.png'),'environment':environment_versions(),
                                   'isolation':isolation,'native_scene_sha256':sha(PROJECT/branch/assigned['formal_record']['scene']),
                                   'threads':{x:os.environ[x] for x in ['OPENBLAS_NUM_THREADS','OMP_NUM_THREADS','MKL_NUM_THREADS','NUMEXPR_NUM_THREADS']},
                                   'cache_env':{x:os.environ[x] for x in ['TEMP','TMP','MPLCONFIGDIR','XDG_CACHE_HOME']}},True)
    print(json.dumps({'qid':qid,'eligible':ev['eligible'],'object_count':len(metadata['objects']),'path_ids':list(paths),'environment':environment_versions()},ensure_ascii=False))
else:
    candidate=Path(args.candidate).resolve()
    assert candidate.is_relative_to(root)
    plugin=read_json(candidate/'plugin.json')
    renderer=PluginRenderer(config,adapter,{qid:metadata})
    normalized=renderer.normalize(plugin)
    assert normalized==plugin, 'Plugin must already include the exact defaults before freezing.'
    if args.mode=='render':
        save(candidate/'eligibility_before_render.json',eligible('before_render'),True)
        p1,data1,d1=renderer.render(plugin,frozen=True)
        p2,data2,d2=renderer.render(plugin,frozen=True)
        assert p1==p2==plugin and data1==data2 and d1==d2
        (candidate/'candidate.png').write_bytes(data1)
        save(candidate/'context.json',metadata,True)
        save(candidate/'path_fingerprints.json',paths,True)
        save(candidate/'render_check.json',{'fresh_schema':True,'normalized_exact':True,'noop_pixels_equal':True,
             'repeat_png_bytes_equal':True,'image_sha256':sha(candidate/'candidate.png'),'pixel_sha256':d1,
             'plugin_sha256':sha(candidate/'plugin.json'),'context_sha256':sha(candidate/'context.json'),
             'paths_sha256':sha(candidate/'path_fingerprints.json'),'environment':environment_versions(),
             'adapter_file':str(Path(__import__(RendererAdapter.__module__).__file__)),
             'plugin_renderer_file':str(Path(__import__(PluginRenderer.__module__).__file__)),
             'schema_sha256':sha(PROJECT/branch/'workbench/plugin.schema.json'),'isolation':isolation},True)
        print(json.dumps({'qid':qid,'rendered':True,'sha256':sha(candidate/'candidate.png')}))
    else:
        # Independent process: all exact JSON values, path order, geometry and images must match.
        old_context=read_json(candidate/'context.json')
        current_context=json.loads(json.dumps(metadata))
        assert current_context==old_context, 'fresh context drift'
        assert json.loads(json.dumps(paths))==read_json(candidate/'path_fingerprints.json'), 'fresh paths drift'
        p,data,digest=renderer.render(plugin,frozen=True)
        assert data==(candidate/'candidate.png').read_bytes(), 'fresh replay PNG byte drift'
        check=read_json(candidate/'render_check.json')
        assert digest==check['pixel_sha256']
        assert environment_versions()==check['environment']
        save(candidate/'fresh_process_replay.json',{'checked_at':now(),'pid':os.getpid(),'context_json_exact':True,'paths_json_exact':True,
             'png_bytes_exact':True,'image_sha256':sha(candidate/'candidate.png'),'pixel_sha256':digest,'environment':environment_versions()},True)
        print(json.dumps({'qid':qid,'fresh_process_replay_exact':True,'pid':os.getpid()}))
